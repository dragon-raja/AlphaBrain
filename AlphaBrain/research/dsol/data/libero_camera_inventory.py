"""CPU-only LIBERO / Plus camera inventory; never imports a simulator or policy."""
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from .artifacts import read, sha, write, path_mapping


def parse_camera_task(name):
    base, parameters = name.rsplit('_view_', 1)
    angles, state = parameters.split('_initstate_', 1)
    values = [int(value) for value in angles.split('_')]
    if len(values) != 5 or '_noise_' in state:
        raise ValueError('Not a pure camera task identifier')
    state = int(state)
    return dict(base_task=base, horizon=values[0], vertical=values[1],
                distance_scale=values[2]/100., endpoint_yaw=values[3],
                endpoint_pitch=values[4], robot_initial_variant=state)


def inventory(locations_file, output, *, path_mappings=(), workers=4):
    """Audit reusable identities, not full dataset bytes or runtime completeness."""
    output=Path(output)
    if output.exists():raise FileExistsError(output)
    locations=read(locations_file)['resource_paths']
    runtime=Path(locations['libero_plus_runtime'])
    base=runtime/'libero/libero'
    classification=base/'benchmark/task_classification.json'
    definitions=read(classification)
    with path_mapping(path_mappings):
        release_file=Path(locations['libero_frozen_matrix'])/'release.json'
        release=read(release_file)
        states=release['states']
        evaluated_tasks={(state['suite'],Path(state['bddl_file']).stem) for state in states}
        checks=[]
        for file,expected in release['initial_source_hashes'].items():
            checks.append((file,expected))
        def verify(item):
            file,expected=item
            exists=Path(file).is_file()
            return dict(path=file,expected_sha256=expected,
                        status='PASS' if exists and sha(file)==expected else 'MISSING_OR_CHANGED')
        with ThreadPoolExecutor(max_workers=workers) as pool:
            initial_checks=list(pool.map(verify,checks))
    rows=[]
    for suite,tasks in definitions.items():
        for task in tasks:
            if task['category']!='Camera Viewpoints':continue
            parsed=parse_camera_task(task['name'])
            bddl=base/'bddl_files'/suite/(parsed['base_task']+'.bddl')
            initial=base/'init_files'/suite/(parsed['base_task']+'.pruned_init')
            rows.append(dict(suite=suite,**task,**parsed,bddl=str(bddl),initial_file=str(initial),
                resource_files_present=bddl.is_file() and initial.is_file(),
                base_task_in_previous_matrix=(suite,parsed['base_task']) in evaluated_tasks))
    sources=sorted({r['bddl'] for r in rows}|{r['initial_file'] for r in rows})
    with ThreadPoolExecutor(max_workers=workers) as pool:
        source_records=list(pool.map(lambda path:dict(path=path,sha256=sha(path))
            if Path(path).is_file() else dict(path=path,status='MISSING'),sources))
    wrapper=base/'envs/env_wrapper.py'
    result=dict(status='CPU_INVENTORY_COMPLETE',runtime_validated=False,
        source=dict(locations_sha256=sha(locations_file),classification_sha256=sha(classification),
                    wrapper_sha256=sha(wrapper),release_sha256=sha(release_file)),
        existing_matrix=dict(tasks=len(evaluated_tasks),initials=len(states),
            candidates=release['candidate_count'],execution_repeats=release['noise_repeats'],
            models=release['models'],holdout=release['holdout'],
            initial_identity_checks=initial_checks,
            status='PASS' if all(r['status']=='PASS' for r in initial_checks) else 'HOLD'),
        plus_camera=dict(total_entries=len(rows),by_suite=dict(Counter(r['suite'] for r in rows)),
            base_tasks=len({(r['suite'],r['base_task']) for r in rows}),
            missing_resource_entries=sum(not r['resource_files_present'] for r in rows),
            entries_on_previous_eight_tasks=sum(r['base_task_in_previous_matrix'] for r in rows),
            nonzero_robot_variants=sum(r['robot_initial_variant']!=0 for r in rows),
            source_files=source_records),
        distinctions=[
            'The existing 97-view matrix is a custom catalog, not the official Plus camera test set.',
            'Plus camera identifiers encode five camera parameters; wrapper resolves the original BDDL.',
            'Resource presence and hashing do not certify full Plus datasets or new policy results.',
            'Historical LIBERO heldout initials are not proven training-disjoint tasks or states.',
            'No camera trajectories, multi-window Accel or new successes are generated by this audit.'],
        next_cpu_steps=['Freeze base task / initial / camera mappings before any Plus evaluation.',
                        'Separate controllable extrinsics from optics; preserve the original catalog for reporting.',
                        'Use old LIBERO results for descriptive strata only, not fresh confirmation.'])
    output.mkdir(parents=True,exist_ok=False)
    write(output/'camera-entries.json',rows)
    result['camera_entries_sha256']=sha(output/'camera-entries.json')
    write(output/'summary.json',result)
    return result
